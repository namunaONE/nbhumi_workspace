Future<void> main() async {
  final binding = WidgetsFlutterBinding.ensureInitialized();
  // Hold the static native splash (brand blue + glyph, generated by
  // flutter_native_splash) while Supabase and the onboarding gate load, so
  // there is no white flash before the animated Flutter splash takes over.
  FlutterNativeSplash.preserve(widgetsBinding: binding);

  await Supabase.initialize(
    url: EnvConfig.supabaseUrl,
    publishableKey: EnvConfig.supabasePublishableKey,
    // DeepLinkListener owns the PKCE exchange. Supabase Flutter also installs
    // an app_links listener by default; two listeners would redeem the same
    // one-time code and make cold/warm confirmation links fail
    // nondeterministically.
    authOptions: const FlutterAuthClientOptions(detectSessionInUri: false),
  );
  final seen = await OnboardingGate.loadSeen();
  final initialLocale = await AppLocaleNotifier.loadLocale();
  final initialThemeMode = await AppThemeNotifier.loadThemeMode();

  runApp(
    ProviderScope(
      overrides: [
        onboardingGateProvider.overrideWith((ref) {
          final gate = OnboardingGate(seen: seen);
          ref.onDispose(gate.dispose);
          return gate;
        }),
        initialLocaleProvider.overrideWithValue(initialLocale),
        initialThemeModeProvider.overrideWithValue(initialThemeMode),
      ],
      // AppProviderObserver records provider failures into AppLogger.
      // Session attribution is a provider rather than a second observer,
      // because it needs a Ref to watch the session and ProviderObserver
      // deliberately does not expose one.
      observers: <ProviderObserver>[AppProviderObserver()],
      child: const UserApp(),
    ),
  );
}

/// True inside `flutter test`, where the native splash plugin is unregistered
/// and the Lottie ticker would keep `pumpAndSettle` from ever settling.
bool get _splashBypassed {
  // kIsWeb first: dart:io is unavailable on web, and this app is mobile,
  // so the guard is purely defensive for future targets.
  if (kIsWeb) return false;
  return Platform.environment.containsKey('FLUTTER_TEST');
}

/// Root widget for the nBhumi user app.
///
/// Owns nothing but the [MaterialApp] shell: routing comes from
/// [appRouterProvider] so that auth redirects stay in one place.
class UserApp extends ConsumerWidget {
  /// Creates the app shell.
  const UserApp({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    // Watching the bridge here guarantees log entries are attributed from the
    // very first frame, rather than only after something first reads a session.
    ref.watch(sessionLoggingBridgeProvider);
    final router = ref.watch(appRouterProvider);
    final locale = ref.watch(appLocaleProvider);
    final themeMode = ref.watch(appThemeProvider);

    return DeepLinkListener(
      child: MaterialApp.router(
        title: 'nBhumi',
        theme: AppTheme.light,
        darkTheme: AppTheme.dark,
        themeMode: themeMode,
        locale: locale,
        routerConfig: router,
        // Wired now so M3's Nepali localisation only has to add .arb files
        // rather than also reworking every app entry point.
        localizationsDelegates: const <LocalizationsDelegate<Object>>[
          AppLocalizations.delegate,
          auth_strings.AppLocalizations.delegate,
          kyc_strings.AppLocalizations.delegate,
          notif_strings.AppLocalizations.delegate,
          post_strings.AppLocalizations.delegate,
          detail_strings.AppLocalizations.delegate,
          search_strings.AppLocalizations.delegate,
          GlobalMaterialLocalizations.delegate,
          GlobalWidgetsLocalizations.delegate,
          GlobalCupertinoLocalizations.delegate,
        ],
        supportedLocales: const <Locale>[Locale('en'), Locale('ne')],
        builder: (context, child) {
          // Widget tests pump the full app (Rule 33 forbids real backends
          // but not the shell): hiding content behind a 3s animation would
          // break every one of them, so tests skip straight to the content.
          return SplashScreen(
            enabled: !_splashBypassed,
            child: child ?? const SizedBox.shrink(),
          );
        },
      ),
    );
  }
}

/// Shows the Lottie splash animation on first frame, then reveals [child].
///
/// Sequence: static native splash (held by `preserve` in [main]) → this
/// animated handoff → app content. The native splash is removed the moment
/// the animation frame mounts, so the static glyph never flashes over the
/// animation start.
class SplashScreen extends StatefulWidget {
  /// Creates the splash screen wrapper.
  const SplashScreen({
    required this.child,
    super.key,
    this.enabled = true,
    this.animationAsset = 'assets/animations/splash.json',
    this.fallbackTimeout = AppDurations.splashFallback,
  });

  /// The app content to show after the splash.
  final Widget child;

  /// When false, renders [child] immediately. Production passes false only
  /// under `flutter test`; widget tests pass explicit values.
  final bool enabled;

  /// Lottie animation asset. Injectable so tests can force the error path.
  final String animationAsset;

  /// Backstop dismiss when the composition never loads. Must exceed the
  /// animation length (90 frames @ 30fps = 3s) plus load margin.
  final Duration fallbackTimeout;

  @override
  State<SplashScreen> createState() => _SplashScreenState();
}

class _SplashScreenState extends State<SplashScreen> {
  bool _showSplash = true;

  @override
  void initState() {
    super.initState();
    if (!widget.enabled) {
      _showSplash = false;
      return;
    }
    // Hand off from the static native splash to the animation the moment
    // this frame mounts. Skipped under test (plugin unregistered there).
    if (!_splashBypassed) {
      FlutterNativeSplash.remove();
    }
    // Backstop: a missing or unloadable composition must never trap the
    // user on the splash — `onLoaded` dismisses earlier on the happy path.
    Future.delayed(widget.fallbackTimeout, _dismiss);
  }

  /// Single dismiss path: both timers funnel here, and the guard makes the
  /// second one a no-op so a late composition load cannot rebuild twice.
  void _dismiss() {
    if (!mounted || !_showSplash) return;
    setState(() => _showSplash = false);
  }

  @override
  Widget build(BuildContext context) {
    if (!_showSplash) return widget.child;

    return Stack(
      children: [
        Container(color: BrandColors.logoBlue),
        Center(
          child: Lottie.asset(
            widget.animationAsset,
            width: AppSizes.splashGlyph,
            height: AppSizes.splashGlyph,
            fit: BoxFit.contain,
            // A corrupt or missing composition degrades to the static
            // wordmark rather than Flutter's red error box — the splash is
            // the brand's first impression, never a crash screen.
            errorBuilder: (context, error, stackTrace) =>
                const _StaticWordmark(),
            onLoaded: (composition) {
              // Dismiss shortly after the animation completes; the initState
              // backstop covers the case where this never fires.
              Future.delayed(
                composition.duration + AppDurations.splashBuffer,
                _dismiss,
              );
            },
          ),
        ),
      ],
    );
  }
}

/// Static brand fallback when the Lottie composition cannot load.
class _StaticWordmark extends StatelessWidget {
  const _StaticWordmark();

  @override
  Widget build(BuildContext context) {
    return const Text(
      'nBhumi',
      style: TextStyle(
        // White on brand blue ≈13:1; kept literal — no onScrim-style role
        // exists for brand-surface content (Rule 43 exception, documented).
        color: Colors.white,
        fontSize: 48,
        fontWeight: FontWeight.w700,
        letterSpacing: 1.2,
      ),
    );
  }
}
